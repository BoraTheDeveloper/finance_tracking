export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'km';
}

export function t(language: Language, key: TranslationKey, values: Record<string, string | number> = {}) {
  const template = (language === 'km' ? KM[key] : undefined) ?? EN[key];
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function categoryLabel(category: Pick<Category, 'key' | 'label'>, language: Language) {
  return DEFAULT_CATEGORY_LABELS[category.key]?.[language] ?? category.label;
}
